"""Доп. инструменты — отдельная вкладка, основной экран остаётся финансовым результатом."""

import streamlit as st


def render():
    st.title("Доп. инструменты")
    st.caption("Инструменты сверх расчёта финансового результата. Появятся здесь по мере готовности.")
    for title, text in [
        ("Калькулятор цены", "Цена продажи под целевую маржу и ДРР на фактических комиссиях, логистике и "
                             "проценте выкупа каждого товара."),
        ("Рекомендации к отгрузке FBO/FBW", "Какие товары и сколько везти на склады маркетплейса, исходя из "
                                            "прибыли на штуку и скорости продаж."),
        ("Когортный учёт рекламы", "Реклама и выкупы, привязанные к неделе заказа: показывает итог недели без "
                                   "перекоса «реклама уже списана, а выкупов ещё нет»."),
    ]:
        with st.container(border=True):
            st.markdown(f"**{title}** · в разработке")
            st.caption(text)
